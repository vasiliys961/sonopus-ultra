export function translateEngineText(locale: Locale, text: string): string {
  if (locale === 'ru' || !text) return text
  const exact = exactEnglish[text]
  if (exact) return exact
  for (const rule of patterns) {
    const match = text.match(rule.pattern)
    if (match) return rule.english(match)
  }
  return text
}
